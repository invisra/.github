#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

function argument(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : fallback;
}

const configPath = argument("--config", "api-reference.config.json");
const check = process.argv.includes("--check");

if (!fs.existsSync(configPath)) {
  console.error(`API reference generator config not found: ${configPath}`);
  process.exit(1);
}

const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
const manifestPath = config.manifest ?? "api-coverage.json";
const outputPath = config.output ?? "docs/api-reference.md";
const profile = config.profile ?? "standard";
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));

function standardReference() {
  const lines = [
    `# ${manifest.vendor} API reference`,
    "",
    "> Generated from `api-coverage.json`. Do not edit this file manually.",
    "",
    `Verified against cited upstream sources: **${manifest.verifiedAt}**`,
    "",
    "| ID | Family | Operation | HTTP | TypeScript | Python | Classification | Retry | Confirmation |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const op of manifest.operations) {
    const http = op.method && op.path ? `\`${op.method} ${op.path}\`` : "—";
    const typescript = op.typescript ? `\`${op.typescriptSymbol}\`` : "—";
    const python = op.python ? `\`${op.pythonSymbol}\`` : "—";
    lines.push(
      `| \`${op.id}\` | ${op.family} | ${op.operation} | ${http} | ${typescript} | ${python} | ${op.classification} | ${op.retryPolicy} | ${op.confirmationRequired ? "required" : "no"} |`,
    );
  }

  lines.push(
    "",
    "## Semantics",
    "",
    "- `safe` retry policy is reserved for operations declared idempotent by the coverage manifest.",
    "- `confirmationRequired` marks operations that require explicit caller confirmation before execution.",
    "- Source confidence, idempotency, and additional contract metadata remain authoritative in `api-coverage.json`.",
    "",
  );
  return lines;
}

function digikeyReference() {
  const verified = manifest.operations.filter((op) => !op.experimental);
  const experimental = manifest.operations.filter((op) => op.experimental);
  const lines = [
    `# ${manifest.vendor} API reference`,
    "",
    "> Generated from `api-coverage.json`. Do not edit this file manually.",
    "",
    `Verified against cited upstream sources: **${manifest.verifiedAt}**`,
    "",
    `Operations: **${manifest.operations.length} total** — **${verified.length} verified/public** and **${experimental.length} experimental/inferred**.`,
    "",
    "## Verified/public operations",
    "",
    "| ID | Family | TypeScript | Python | Classification | Retry |",
    "| --- | --- | --- | --- | --- | --- |",
  ];

  for (const op of verified) {
    lines.push(`| \`${op.id}\` | ${op.family} | \`${op.typescriptSymbol}\` | \`${op.pythonSymbol}\` | ${op.classification} | ${op.retryPolicy} |`);
  }

  lines.push(
    "",
    "## Experimental/inferred operations",
    "",
    "> These operations are not treated as verified contracts. They require the explicit unverified-API opt-in shown below; consequential mutations also require confirmation.",
    "",
    "| ID | Family | TypeScript | Python | Classification | Retry | Guard |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  );

  for (const op of experimental) {
    lines.push(`| \`${op.id}\` | ${op.family} | \`${op.typescriptSymbol}\` | \`${op.pythonSymbol}\` | ${op.classification} | ${op.retryPolicy} | \`${op.guard}\` |`);
  }

  lines.push(
    "",
    "## Semantics",
    "",
    "- `safe` retry policy is reserved for operations declared idempotent by the coverage manifest.",
    "- Experimental/inferred operations remain guarded even when they are read-only.",
    "- Consequential experimental operations require both the unverified-API opt-in and explicit confirmation.",
    "- `api-coverage.json` remains authoritative for HTTP method/path, source confidence, idempotency, authentication, notes, and drift metadata.",
    "",
  );
  return lines;
}

function jlcpcbReference() {
  const lines = [
    `# ${manifest.vendor} API reference`,
    "",
    "> Generated from `api-coverage.json`. Do not edit this file manually.",
    "",
    `Verified against cited upstream sources: **${manifest.verifiedAt}**`,
    "",
    "| ID | Family | Operation | HTTP | TypeScript | Python | Confidence | Classification | Retry | Confirmation |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const op of manifest.operations) {
    const http = op.method && op.path ? `\`${op.method} ${op.path}\`` : op.method ? `\`${op.method}\` (caller path)` : "—";
    const typescript = op.typescript ? `\`${op.typescriptSymbol}\`` : "—";
    const python = op.python ? `\`${op.pythonSymbol}\`` : "—";
    lines.push(
      `| \`${op.id}\` | ${op.family} | ${op.operation} | ${http} | ${typescript} | ${python} | ${op.confidence} | ${op.classification} | ${op.retryPolicy} | ${op.confirmationRequired ? "required" : "no"} |`,
    );
  }

  lines.push(
    "",
    "## Semantics",
    "",
    "- `safe` retry policy is reserved for operations declared idempotent by the coverage manifest.",
    "- `confirmationRequired` marks consequential operations that require explicit caller confirmation before execution.",
    "- `cross-referenced` operations are implemented from the best available contract evidence but are not backed by a public machine-readable JLCPCB schema.",
    "- `caller-verified` operations require the caller to supply details obtained from an approved developer console.",
    "- `api-coverage.json` remains authoritative for source confidence, idempotency, notes, and drift metadata.",
    "",
  );
  return lines;
}

function mouserReference() {
  const deprecated = manifest.operations.filter((op) => op.deprecated);
  const lines = [
    `# ${manifest.vendor} API reference`,
    "",
    "> Generated from `api-coverage.json`. Do not edit this file manually.",
    "",
    `Verified against official Swagger sources: **${manifest.verifiedAt}**`,
    "",
    `Operations: **${manifest.operations.length} total** — **${deprecated.length} deprecated**.`,
    "",
    "| ID | Family | HTTP | TypeScript | Python | Classification | Retry | Status |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const op of manifest.operations) {
    const status = op.deprecated ? "deprecated" : "current";
    lines.push(`| \`${op.id}\` | ${op.family} | \`${op.method} ${op.path}\` | \`${op.typescriptSymbol}\` | \`${op.pythonSymbol}\` | ${op.classification} | ${op.retryPolicy} | ${status} |`);
  }

  lines.push(
    "",
    "## Contract and model governance",
    "",
    "- `api-coverage.json` is the authoritative operation inventory and semantic metadata source.",
    "- Mouser's official V1/V2 Swagger documents are compared against checked-in baselines under `specs/` for operation and structural model drift.",
    "- Checked-in Swagger baselines drive generated TypeScript and Python models; normal CI verifies generated code remains synchronized when spec/codegen inputs change.",
    "- `safe` retry policy is reserved for operations declared idempotent by the coverage manifest.",
    "- Consequential order operations require explicit confirmation and are not automatically retried.",
    "",
  );
  return lines;
}

const renderers = {
  standard: standardReference,
  digikey: digikeyReference,
  jlcpcb: jlcpcbReference,
  mouser: mouserReference,
};

const render = renderers[profile];
if (!render) {
  console.error(`Unknown API reference profile: ${profile}`);
  process.exit(1);
}

const expected = `${render().join("\n")}\n`;
if (check) {
  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (actual !== expected) {
    console.error(`${outputPath} is stale. Run: node scripts/generate-api-reference.mjs`);
    process.exit(1);
  }
  console.log(`${outputPath} is up to date.`);
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected);
  console.log(`Generated ${outputPath}.`);
}
